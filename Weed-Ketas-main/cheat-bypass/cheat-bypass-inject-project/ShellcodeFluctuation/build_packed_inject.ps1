param(
    [string]$RawBlob = (Join-Path $PSScriptRoot 'loader.bin'),
    [string]$PackedBlob = (Join-Path $PSScriptRoot 'loader.pak.bin'),
    [string]$KeyHeader = (Join-Path $PSScriptRoot 'sckey.h'),
    [string]$PackedHeader = (Join-Path $PSScriptRoot 'Bytes.hpp'),
    [uint32]$Key = 0
)

$ErrorActionPreference = 'Stop'

$packerSource = Join-Path $PSScriptRoot '..\..\cheat-bypass-loader\tools\pack_bin.cpp'
$packerCache = Join-Path $env:TEMP 'opencode\pack_bin'
$packer = Join-Path $packerCache 'pack_bin.exe'
New-Item -ItemType Directory -Path $packerCache -Force | Out-Null

$sourceInfo = Get-Item -LiteralPath $packerSource -ErrorAction Stop
$rebuildPacker = -not (Test-Path -LiteralPath $packer)
if (-not $rebuildPacker) {
    $rebuildPacker = (Get-Item -LiteralPath $packer).LastWriteTimeUtc -lt $sourceInfo.LastWriteTimeUtc
}

if ($rebuildPacker) {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (-not (Test-Path -LiteralPath $vswhere)) {
        $vswhere = Join-Path $env:ProgramFiles 'Microsoft Visual Studio\Installer\vswhere.exe'
    }
    if (-not (Test-Path -LiteralPath $vswhere)) {
        throw 'Visual Studio installation locator not found; cannot build pack_bin.exe outside the source tree.'
    }

    $vsInstall = (& $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath | Select-Object -First 1).Trim()
    $vcvars = Join-Path $vsInstall 'VC\Auxiliary\Build\vcvars64.bat'
    if (-not (Test-Path -LiteralPath $vcvars)) {
        throw "Visual C++ environment script not found: $vcvars"
    }

    $packerObject = Join-Path $packerCache 'pack_bin.obj'
    $compileScript = Join-Path $packerCache 'build_pack_bin.cmd'
    @"
@echo off
call "$vcvars" x64
if errorlevel 1 exit /b 1
cl.exe /nologo /O2 /EHsc /std:c++17 /Fe:"$packer" /Fo:"$packerObject" "$packerSource"
exit /b %errorlevel%
"@ | Set-Content -LiteralPath $compileScript -Encoding ASCII

    & cmd.exe /d /c "`"$compileScript`""
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $packer)) {
        throw "failed to build pack_bin.exe in the temporary tool cache: $packerCache"
    }
}
if (-not (Test-Path -LiteralPath $RawBlob)) {
    throw "raw loader blob not found: $RawBlob"
}

# The repository historically stored the raw blob as a C byte-array dump
# ("unsigned char buf[] = \"\\x..\";") but passed it to pack_bin as if it
# were already binary.  That made the decoded payload start with the ASCII
# bytes for "unsigned" and the remote thread could never execute it.
# Normalize that representation once, in-place, before packing.
$inputBytes = [System.IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $RawBlob))
$looksLikeCByteArray = $false
if ($inputBytes.Length -ge 12) {
    $prefix = [System.Text.Encoding]::ASCII.GetString($inputBytes, 0, [Math]::Min($inputBytes.Length, 128))
    $looksLikeCByteArray = $prefix -match '^\s*(?:(?:const|static)\s+)?unsigned\s+char\s+'
}

if ($looksLikeCByteArray) {
    $source = [System.Text.Encoding]::ASCII.GetString($inputBytes)
    $tokens = [regex]::Matches($source, '\\x([0-9A-Fa-f]{2})')
    if ($tokens.Count -eq 0) {
        throw "C byte-array input contains no \\xHH byte tokens: $RawBlob"
    }

    $normalized = New-Object byte[] $tokens.Count
    for ($i = 0; $i -lt $tokens.Count; $i++) {
        $normalized[$i] = [Convert]::ToByte($tokens[$i].Groups[1].Value, 16)
    }

    [System.IO.File]::WriteAllBytes((Resolve-Path -LiteralPath $RawBlob), $normalized)
    Write-Host ("normalized C byte-array {0} -> {1} raw bytes in {2}" -f $inputBytes.Length, $normalized.Length, $RawBlob)
}

$rawBytes = [System.IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $RawBlob))
if ($rawBytes.Length -lt 16) {
    throw "raw payload is too small after normalization: $($rawBytes.Length) bytes"
}
if ($rawBytes[0] -eq [byte][char]'u' -and
    $rawBytes[1] -eq [byte][char]'n' -and
    $rawBytes[2] -eq [byte][char]'s' -and
    $rawBytes[3] -eq [byte][char]'i') {
    throw "raw payload still appears to be source text; refusing to pack it"
}

# Use a fresh non-zero 32-bit seed for each build.  The key is written to the
# source header and the same key is used for the resource transformation.
$key = $Key
if ($key -eq 0) {
    $key = [uint32](Get-Random -Minimum 1 -Maximum 0x7FFFFFFF)
}
$keyText = '0x{0:X8}u' -f $key

$previousErrorAction = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
& $packer $RawBlob ('0x{0:X8}' -f $key) $PackedBlob 2>&1 | ForEach-Object {
    Write-Host $_
}
$packExit = $LASTEXITCODE
$ErrorActionPreference = $previousErrorAction
if ($packExit -ne 0) {
    throw "packing failed with exit code $packExit"
}

$header = @"
#pragma once
#include <cstdint>

// 32-bit seed for the packed loader blob embedded in Bytes.hpp.
// Generated by build_packed_inject.ps1; it must match loader.pak.bin.
inline constexpr uint32_t kScKey = $keyText;
"@
[System.IO.File]::WriteAllText(
    $KeyHeader,
    $header,
    [System.Text.UTF8Encoding]::new($false))

function Write-PackedBytesHeader {
    param(
        [byte[]]$Data,
        [string]$Path
    )

    $lines = New-Object 'System.Collections.Generic.List[string]'
    [void]$lines.Add('#pragma once')
    [void]$lines.Add('#include <cstddef>')
    [void]$lines.Add('')

    # Keep two chunks to preserve the existing bytes.cpp interface while
    # ensuring that the generated source contains only the packed bytes.
    $chunkSize = [int][Math]::Ceiling($Data.Length / 2.0)
    for ($chunkIndex = 0; $chunkIndex -lt 2; $chunkIndex++) {
        $start = $chunkIndex * $chunkSize
        $end = [Math]::Min($start + $chunkSize, $Data.Length)
        $name = "kPayloadChunk$chunkIndex"
        [void]$lines.Add("static const unsigned char $name[] =")

        for ($offset = $start; $offset -lt $end; $offset += 32) {
            $lineEnd = [Math]::Min($offset + 32, $end)
            $literal = ''
            for ($i = $offset; $i -lt $lineEnd; $i++) {
                $literal += ('\x{0:X2}' -f [int]$Data[$i])
            }
            $suffix = if ($lineEnd -eq $end) { ';' } else { '' }
            [void]$lines.Add(('    "' + $literal + '"' + $suffix))
        }
        [void]$lines.Add('')
    }

    [System.IO.File]::WriteAllText(
        $Path,
        (($lines -join [Environment]::NewLine) + [Environment]::NewLine),
        [System.Text.UTF8Encoding]::new($false))
}

$packedData = [System.IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $PackedBlob))
Write-PackedBytesHeader -Data $packedData -Path $PackedHeader

Write-Host ("packed {0} bytes with key {1}; generated {2}" -f $packedData.Length, $keyText, $PackedHeader)
