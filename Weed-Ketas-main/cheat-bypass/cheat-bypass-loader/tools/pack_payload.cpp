// pack_payload.cpp — pre-build packer: Weed.exe → payload.inc (XOR+rol8 obfuscation)
// cl /O2 /EHsc /std:c++17 pack_payload.cpp /Fe:pack.exe
#include <cstdio>
#include <cstdint>
#include <cstdlib>
#include <vector>

int main(int argc, char** argv)
{
    if (argc != 4) {
        std::fprintf(stderr, "usage: pack <in.bin> <key_u32_hex_or_dec> <out.inc>\n");
        return 1;
    }
    std::FILE* fi = std::fopen(argv[1], "rb");
    if (!fi) { std::fprintf(stderr, "cannot open %s\n", argv[1]); return 2; }
    std::fseek(fi, 0, SEEK_END);
    long n = std::ftell(fi);
    std::fseek(fi, 0, SEEK_SET);
    if (n <= 0) { std::fclose(fi); return 3; }
    std::vector<uint8_t> buf(n);
    std::fread(buf.data(), 1, n, fi);
    std::fclose(fi);

    uint32_t key = (uint32_t)std::strtoul(argv[2], nullptr, 0);
    if (!key) key = 0xA3C5F17B;

    uint32_t s = key;
    for (long i = 0; i < n; ++i) {
        s ^= s << 13; s ^= s >> 17; s ^= s << 5;        // xorshift32
        uint8_t v = buf[i] ^ (uint8_t)(s & 0xFF);
        v = (uint8_t)((v << 3) | (v >> 5));              // rol8 by 3
        buf[i] = v;
    }

    std::FILE* fo = std::fopen(argv[3], "wb");
    if (!fo) { std::fprintf(stderr, "cannot write %s\n", argv[3]); return 4; }
    std::fprintf(fo, "// auto-generated by tools/pack.exe. do not edit.\n");
    std::fprintf(fo, "#pragma once\n#include <cstdint>\n#include <cstddef>\n\n");
    std::fprintf(fo, "namespace payload {\n");
    std::fprintf(fo, "inline constexpr uint32_t     kKey  = 0x%08Xu;\n", key);
    std::fprintf(fo, "inline constexpr std::size_t  kSize = %ldu;\n", n);
    std::fprintf(fo, "alignas(16) inline constexpr uint8_t kData[%ld] = {", n);
    for (long i = 0; i < n; ++i) {
        if ((i & 15) == 0) std::fprintf(fo, "\n    ");
        std::fprintf(fo, "0x%02X,", buf[i]);
    }
    std::fprintf(fo, "\n};\n} // namespace payload\n");
    std::fclose(fo);

    std::fprintf(stderr, "pack: %ld bytes -> %s (key=0x%08X)\n", n, argv[3], key);
    return 0;
}
